create or replace function public._notify_achievement_unlocked()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform public._notify_user(
    new.user_id,
    'achievement',
    'Conquista desbloqueada',
    'Você desbloqueou "' || public._notification_achievement_name(new.achievement_key) || '". A banca registrou o feito.',
    'progresso',
    new.achievement_key,
    jsonb_build_object('achievement_key', new.achievement_key)
  );
  return new;
end;
$$;

drop trigger if exists taihenbet_notify_achievement on public.user_achievements;
create trigger taihenbet_notify_achievement
after insert on public.user_achievements
for each row execute function public._notify_achievement_unlocked();

-- ---------- Titulos ----------
create or replace function public._notify_title_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.equipped_title_key is distinct from new.equipped_title_key then
    perform public._notify_user(
      new.id,
      'title',
      case when new.equipped_title_key is null then 'Título removido' else 'Título equipado' end,
      case when new.equipped_title_key is null
        then 'Seu perfil voltou a circular sem título oficial.'
        else 'Seu perfil agora exibe "' || public._notification_title_name(new.equipped_title_key) || '".'
      end,
      'progresso',
      new.equipped_title_key,
      jsonb_build_object('achievement_key', new.equipped_title_key)
    );
  end if;
  return new;
end;
$$;

drop trigger if exists taihenbet_notify_title_change on public.profiles;
create trigger taihenbet_notify_title_change
after update of equipped_title_key on public.profiles
for each row execute function public._notify_title_change();

-- ---------- Moderacao ----------
create or replace function public._notify_moderation_log()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_title text;
  v_message text;
  v_page text;
begin
  if new.target_user_id is null then return new; end if;

  case new.action
    when 'user_suspended' then
      v_title := 'Conta suspensa pela banca';
      v_message := 'Sua conta foi suspensa. Motivo: ' || coalesce(new.details->>'reason', 'não informado') || '.';
      v_page := 'inicio';
    when 'user_reactivated' then
      v_title := 'Conta reativada';
      v_message := 'A banca devolveu o acesso às operações da sua conta.';
      v_page := 'inicio';
    when 'museum_post_removed' then
      v_title := 'Peça removida do Museu';
      v_message := 'Uma publicação sua foi removida pela Central de Moderação.';
      v_page := 'museu';
    when 'tai_message_removed' then
      v_title := 'Mensagem removida';
      v_message := 'Uma mensagem sua em Para a Tai foi removida pela Central de Moderação.';
      v_page := 'para-tai';
    else
      return new;
  end case;

  perform public._notify_user(
    new.target_user_id, 'moderation', v_title, v_message,
    v_page, new.target_id,
    jsonb_build_object('action', new.action, 'moderator', new.actor_name)
  );
  return new;
end;
$$;

drop trigger if exists taihenbet_notify_moderation on public.admin_moderation_log;
create trigger taihenbet_notify_moderation
after insert on public.admin_moderation_log
for each row execute function public._notify_moderation_log();

-- ---------- Bilhetes esportivos ----------
create or replace function public._notify_sports_bet_settlement()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.status = 'pending' and new.status in ('won','lost') then
    perform public._notify_user(
      new.user_id,
      'sports_result',
      case when new.status = 'won' then 'Bilhete esportivo venceu' else 'Bilhete esportivo perdeu' end,
      case when new.status = 'won'
        then 'A banca liquidou seu bilhete vencedor. Pagamento: ' || trim(to_char(coalesce(new.payout, 0), 'FM999999990D00')) || ' TaiCoins.'
        else 'A banca liquidou seu bilhete como perdido. Stake: ' || trim(to_char(coalesce(new.stake, 0), 'FM999999990D00')) || ' TaiCoins.'
      end,
      'historico',
      new.id::text,
      jsonb_build_object('status', new.status, 'stake', new.stake)
    );
  end if;
  return new;
end;
$$;

do $$
begin
  if to_regclass('public.sports_bets') is not null then
    execute 'drop trigger if exists taihenbet_notify_sports_settlement on public.sports_bets';
    execute 'create trigger taihenbet_notify_sports_settlement after update of status on public.sports_bets for each row execute function public._notify_sports_bet_settlement()';
  end if;
end $$;

