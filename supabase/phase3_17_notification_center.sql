create table if not exists public.user_notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  type text not null default 'system',
  title text not null,
  message text not null,
  target_page text,
  target_entity_id text,
  metadata jsonb not null default '{}'::jsonb,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists user_notifications_user_created_idx
  on public.user_notifications (user_id, created_at desc);
create index if not exists user_notifications_user_unread_idx
  on public.user_notifications (user_id, created_at desc)
  where read_at is null;

-- Habilita entrega em tempo real quando o projeto usa a publicação padrão do Supabase.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (
       select 1
       from pg_publication_tables
       where pubname = 'supabase_realtime'
         and schemaname = 'public'
         and tablename = 'user_notifications'
     ) then
    execute 'alter publication supabase_realtime add table public.user_notifications';
  end if;
end $$;

alter table public.user_notifications enable row level security;
revoke all on table public.user_notifications from anon, authenticated;
grant select on table public.user_notifications to authenticated;

drop policy if exists "users read own notifications" on public.user_notifications;
create policy "users read own notifications"
on public.user_notifications
for select
to authenticated
using (auth.uid() = user_id);

create or replace function public._notify_user(
  p_user_id uuid,
  p_type text,
  p_title text,
  p_message text,
  p_target_page text default null,
  p_target_entity_id text default null,
  p_metadata jsonb default '{}'::jsonb
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id bigint;
begin
  if p_user_id is null then return null; end if;

  insert into public.user_notifications (
    user_id, type, title, message, target_page, target_entity_id, metadata
  ) values (
    p_user_id,
    left(coalesce(nullif(trim(p_type), ''), 'system'), 40),
    left(coalesce(nullif(trim(p_title), ''), 'Comunicado da banca'), 120),
    left(coalesce(nullif(trim(p_message), ''), 'A Entidade registrou um novo evento.'), 700),
    nullif(left(trim(coalesce(p_target_page, '')), 50), ''),
    nullif(left(trim(coalesce(p_target_entity_id, '')), 160), ''),
    case when jsonb_typeof(coalesce(p_metadata, '{}'::jsonb)) = 'object'
      then coalesce(p_metadata, '{}'::jsonb) else '{}'::jsonb end
  ) returning id into v_id;

  return v_id;
end;
$$;
revoke all on function public._notify_user(uuid,text,text,text,text,text,jsonb) from public;

create or replace function public.push_my_notification(
  p_type text,
  p_title text,
  p_message text,
  p_target_page text default null,
  p_target_entity_id text default null,
  p_metadata jsonb default '{}'::jsonb
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_type text := lower(trim(coalesce(p_type, 'system')));
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  if v_type not in ('game_result','bonus','system') then
    raise exception 'Client notification type not allowed';
  end if;

  return public._notify_user(
    v_uid, v_type, p_title, p_message,
    p_target_page, p_target_entity_id, p_metadata
  );
end;
$$;
revoke all on function public.push_my_notification(text,text,text,text,text,jsonb) from public;
grant execute on function public.push_my_notification(text,text,text,text,text,jsonb) to authenticated;

create or replace function public.get_my_notifications(p_limit integer default 60)
returns table (
  id bigint,
  type text,
  title text,
  message text,
  target_page text,
  target_entity_id text,
  metadata jsonb,
  read_at timestamptz,
  created_at timestamptz
)
language sql
security definer
set search_path = ''
as $$
  select n.id, n.type, n.title, n.message, n.target_page,
         n.target_entity_id, n.metadata, n.read_at, n.created_at
  from public.user_notifications n
  where n.user_id = auth.uid()
  order by n.created_at desc
  limit least(100, greatest(1, coalesce(p_limit, 60)));
$$;
revoke all on function public.get_my_notifications(integer) from public;
grant execute on function public.get_my_notifications(integer) to authenticated;

create or replace function public.mark_my_notification_read(p_notification_id bigint)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.user_notifications
  set read_at = coalesce(read_at, now())
  where id = p_notification_id and user_id = auth.uid();
  return found;
end;
$$;
revoke all on function public.mark_my_notification_read(bigint) from public;
grant execute on function public.mark_my_notification_read(bigint) to authenticated;

create or replace function public.mark_all_my_notifications_read()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare v_count integer;
begin
  update public.user_notifications
  set read_at = now()
  where user_id = auth.uid() and read_at is null;
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;
revoke all on function public.mark_all_my_notifications_read() from public;
grant execute on function public.mark_all_my_notifications_read() to authenticated;

create or replace function public.clear_my_read_notifications()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare v_count integer;
begin
  delete from public.user_notifications
  where user_id = auth.uid() and read_at is not null;
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;
revoke all on function public.clear_my_read_notifications() from public;
grant execute on function public.clear_my_read_notifications() to authenticated;

